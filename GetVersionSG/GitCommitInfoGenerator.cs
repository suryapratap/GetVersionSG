using System;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace GetVersionSG;

[Generator]
public sealed class GitCommitInfoGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidConfiguration = new(
        "GITINFO001",
        "Invalid commit-info file",
        "The first line of '{0}' must contain a namespace",
        "GetVersionSG",
        DiagnosticSeverity.Error,
        true);

    private static readonly DiagnosticDescriptor InvalidGetter = new(
        "GITINFO002",
        "Invalid commit-info getter",
        "The method marked with CommitInfoGetter must be a parameterless static string method with a constant return expression",
        "GetVersionSG",
        DiagnosticSeverity.Error,
        true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var configuration = context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith(".commit-info", StringComparison.OrdinalIgnoreCase))
            .Select(static (file, cancellationToken) =>
            {
                var lines = file.GetText(cancellationToken)?.Lines
                    .Select(line => line.ToString().Trim())
                    .ToArray() ?? Array.Empty<string>();
                return new CommitInfoConfiguration(file.Path, lines.FirstOrDefault() ?? string.Empty);
            });

        var getters = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is MethodDeclarationSyntax method &&
                    method.AttributeLists.Count > 0,
                static (generatorContext, _) => ReadGetter(generatorContext))
            .Where(static getter => getter != null)
            .Select(static (getter, _) => getter!)
            .Collect();

        context.RegisterSourceOutput(configuration.Combine(getters), static (productionContext, input) =>
        {
            var config = input.Left;
            if (string.IsNullOrWhiteSpace(config.Namespace))
            {
                productionContext.ReportDiagnostic(Diagnostic.Create(
                    InvalidConfiguration,
                    Location.None,
                    Path.GetFileName(config.Path)));
                return;
            }

            var metadata = GitMetadata.Read(Path.GetDirectoryName(config.Path) ?? Directory.GetCurrentDirectory());
            var className = Path.GetFileNameWithoutExtension(config.Path);
            foreach (var getter in input.Right)
            {
                if (string.IsNullOrWhiteSpace(getter.Expression))
                    productionContext.ReportDiagnostic(Diagnostic.Create(InvalidGetter, getter.Location));
            }

            var source = SourceWriter.Write(config.Namespace, className, metadata, input.Right);
            productionContext.AddSource(className + ".g.cs", source);
        });

        context.RegisterPostInitializationOutput(static context =>
            context.AddSource("CommitInfoGetterAttribute.g.cs", """
                // <auto-generated />
                namespace GetVersionSG;

                [System.AttributeUsage(System.AttributeTargets.Method, AllowMultiple = false)]
                public sealed class CommitInfoGetterAttribute : System.Attribute
                {
                }
                """));
    }

    private static GetterDefinition? ReadGetter(GeneratorSyntaxContext context)
    {
        var method = (MethodDeclarationSyntax)context.Node;
        if (!method.AttributeLists.SelectMany(list => list.Attributes)
            .Any(attribute => attribute.Name.ToString() is "CommitInfoGetter" or "CommitInfoGetterAttribute"))
            return null;

        if (!method.Modifiers.Any(SyntaxKind.StaticKeyword) ||
            method.ParameterList.Parameters.Count != 0 ||
            method.ReturnType.ToString() != "string")
            return new GetterDefinition(method.Identifier.ValueText, string.Empty, method.GetLocation());

        var expression = method.ExpressionBody?.Expression?.ToString();
        if (expression == null && method.Body?.Statements.Count == 1 &&
            method.Body.Statements[0] is ReturnStatementSyntax returnStatement)
            expression = returnStatement.Expression?.ToString();

        return new GetterDefinition(method.Identifier.ValueText, expression ?? string.Empty, method.GetLocation());
    }

    private sealed class CommitInfoConfiguration
    {
        public CommitInfoConfiguration(string path, string @namespace)
        {
            Path = path;
            Namespace = @namespace;
        }

        public string Path { get; }
        public string Namespace { get; }
    }

    internal sealed class GetterDefinition
    {
        public GetterDefinition(string name, string expression, Location location)
        {
            Name = name;
            Expression = expression;
            Location = location;
        }

        public string Name { get; }
        public string Expression { get; }
        public Location Location { get; }
    }

    internal sealed class GitMetadata
    {
        internal GitMetadata(string commitHash, string tags, string distance, string branchName)
        {
            CommitHash = commitHash;
            Tags = tags;
            Distance = distance;
            BranchName = branchName;
        }

        public string CommitHash { get; }
        public string Tags { get; }
        public string Distance { get; }
        public string BranchName { get; }

        public static GitMetadata Read(string workingDirectory)
        {
            var commitHash = RunGit(workingDirectory, "rev-parse HEAD");
            var nearestTag = RunGit(workingDirectory, "describe --tags --abbrev=0 HEAD");
            var tags = string.IsNullOrWhiteSpace(nearestTag)
                ? string.Empty
                : RunGit(workingDirectory, "tag --points-at " + nearestTag);
            var distance = string.IsNullOrWhiteSpace(nearestTag)
                ? "0"
                : RunGit(workingDirectory, "rev-list --count " + nearestTag + "..HEAD");
            var branch = RunGit(workingDirectory, "rev-parse --abbrev-ref HEAD");

            return new GitMetadata(
                commitHash,
                string.IsNullOrWhiteSpace(tags) ? "" : tags,
                string.IsNullOrWhiteSpace(distance) ? "0" : distance,
                string.IsNullOrWhiteSpace(branch) ? "HEAD" : branch);
        }

        private static string RunGit(string workingDirectory, string arguments)
        {
            try
            {
                using var process = Process.Start(new ProcessStartInfo
                {
                    FileName = "git",
                    Arguments = arguments,
                    WorkingDirectory = workingDirectory,
                    RedirectStandardOutput = true,
                    RedirectStandardError = true,
                    UseShellExecute = false,
                    CreateNoWindow = true
                });

                if (process == null)
                    return string.Empty;

                var output = process.StandardOutput.ReadToEnd().Trim();
                process.WaitForExit();
                return process.ExitCode == 0 ? output : string.Empty;
            }
            catch
            {
                return string.Empty;
            }
        }
    }

    internal static class SourceWriter
    {
        public static string Write(
            string @namespace,
            string className,
            GitMetadata metadata,
            System.Collections.Immutable.ImmutableArray<GetterDefinition> getters = default)
        {
            var builder = new StringBuilder();
            builder.AppendLine("// <auto-generated />");
            builder.AppendLine("#nullable enable");
            builder.Append("namespace ").Append(@namespace).AppendLine(";");
            builder.AppendLine();
            builder.Append("public static class ").Append(className).AppendLine();
            builder.AppendLine("{");
            WriteConstant(builder, "CommitHash", metadata.CommitHash);
            WriteConstant(builder, "Tags", metadata.Tags);
            WriteConstant(builder, "Distance", metadata.Distance);
            WriteConstant(builder, "BranchName", metadata.BranchName);
            if (!getters.IsDefault)
            {
                foreach (var getter in getters)
                    WriteExpression(builder, getter);
            }
            builder.AppendLine("}");
            return builder.ToString();
        }

        private static void WriteConstant(StringBuilder builder, string name, string value) => builder
            .Append("    public const string ")
            .Append(name).Append(" = \"")
            .Append(Escape(value))
            .AppendLine("\";");

        private static void WriteExpression(StringBuilder builder, GetterDefinition getter)
        {
            if (string.IsNullOrWhiteSpace(getter.Expression))
                return;

            builder.Append("    public const string ").Append(getter.Name).Append(" = ")
                .Append(getter.Expression).AppendLine(";");
        }

        private static string Escape(string value) => value
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\r", "\\r")
            .Replace("\n", "\\n");
    }
}